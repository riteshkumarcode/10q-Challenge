export const getCourseBySlug = (slug) => {
  if (!slug) return coursesData[0];
  const normalized = slug.replace(/_/g, '-').toLowerCase();
  return (
    coursesData.find(
      (c) =>
        c.slug === slug ||
        c.slug.toLowerCase() === normalized ||
        c.slug.replace(/_/g, '-').toLowerCase() === normalized ||
        String(c.id) === slug
    ) || coursesData[0]
  );
};
