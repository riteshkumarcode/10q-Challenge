export const getMentorshipBySlug = (slug) => {
  if (!slug) return mentorshipData[0];
  const normalized = slug.replace(/_/g, '-').toLowerCase();
  return (
    mentorshipData.find(
      (m) =>
        m.slug === slug ||
        m.slug.toLowerCase() === normalized ||
        m.slug.replace(/_/g, '-').toLowerCase() === normalized ||
        String(m.id) === slug ||
        m.exam.toLowerCase() === slug.toLowerCase()
    ) || mentorshipData[0]
  );
};
